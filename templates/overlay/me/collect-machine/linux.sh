#!/usr/bin/env bash
# Print a machine file (Markdown) for Linux: OS, desktop, shell, terminal,
# editor, hardware summary, and the versions of common tools, for
# <overlay>/me/machine.md. Read-only; prints to stdout, writes nothing.
#
# Privacy: prints no hostname, user name or home path unless you pass
# --with-identity; the home path and user name are replaced by "~" and
# "<user>" in all other output. Reads no secrets and no configuration files
# of the tools (only their --version output).
#
# linux.sh, macos.sh and windows.ps1 share helpers and the tool list by copy
# (each runs on its own): change all three together.
#
# Usage: bash linux.sh [--with-identity] > machine.md
set -uo pipefail

with_identity=false
case ${1:-} in
  --with-identity) with_identity=true ;;
  "") ;;
  *) echo "usage: linux.sh [--with-identity]" >&2; exit 2 ;;
esac

user=$(id -un 2>/dev/null || echo "")

# scrub: replace the home path and the user name in a line of output
scrub() {
  local s=$1
  if ! $with_identity; then
    [[ -n ${HOME:-} ]] && s=${s//$HOME/\~}
    # only names of 3+ characters, so that short names do not mangle output
    [[ ${#user} -ge 3 ]] && s=${s//$user/<user>}
  fi
  printf '%s' "$s"
}

# row <label> <value>: one list item; "unknown" for an empty value
row() { printf -- '- %s: %s\n' "$1" "$(scrub "${2:-unknown}")"; }

# version <tool> [args...]: first non-empty line of the tool's version output
version() {
  local tool=$1; shift
  command -v "$tool" >/dev/null 2>&1 || return 1
  local out
  # A failing version check (e.g. a version-manager shim without a version)
  # gives no version, so that error output is never printed
  if ! out=$(timeout 5 "$tool" "${@:---version}" 2>&1 </dev/null); then
    printf 'installed (version check failed)'
    return 0
  fi
  out=$(sed '/^[[:space:]]*$/d' <<<"$out" | head -n 1 | cut -c 1-100)
  printf '%s' "${out:-installed}"
}

os=unknown
if [[ -r /etc/os-release ]]; then
  # shellcheck disable=SC1091 # os-release exists on every systemd-based distribution
  os=$(. /etc/os-release && printf '%s' "${PRETTY_NAME:-${NAME:-unknown}}")
fi
login_shell=$(getent passwd "$(id -u)" 2>/dev/null | cut -d: -f7)
mem_kb=$(awk '/^MemTotal:/ {print $2}' /proc/meminfo 2>/dev/null)

terminal=${TERM_PROGRAM:-}
[[ -z $terminal && -n ${KITTY_WINDOW_ID:-} ]] && terminal=kitty
[[ -z $terminal && -n ${WEZTERM_PANE:-} ]] && terminal=WezTerm
[[ -z $terminal && -n ${GNOME_TERMINAL_SCREEN:-} ]] && terminal=gnome-terminal
[[ -z $terminal && -n ${KONSOLE_VERSION:-} ]] && terminal=Konsole
[[ -z $terminal && -n ${ALACRITTY_WINDOW_ID:-} ]] && terminal=Alacritty
[[ -n ${TMUX:-} ]] && terminal="${terminal:-unknown} (inside tmux)"

echo "# Machine"
echo
echo "<!-- Generated by linux.sh on $(date +%Y-%m-%d). Add what a script can't know under"
echo "     \"Known oddities\". -->"
echo
echo "## System"
echo
if $with_identity; then
  row "Host name" "$(hostname 2>/dev/null)"
  row "User" "$user"
  row "Home" "${HOME:-}"
fi
row "OS" "$os"
row "Kernel" "$(uname -r)"
row "Architecture" "$(uname -m)"
row "CPU cores" "$(nproc 2>/dev/null)"
[[ -n $mem_kb ]] && row "Memory" "$((mem_kb / 1024 / 1024)) GiB"
row "Desktop" "${XDG_CURRENT_DESKTOP:-none}"
row "Session type" "${XDG_SESSION_TYPE:-unknown}"
row "Login shell" "$login_shell"
row "Shell running this script" "bash ${BASH_VERSION}"
row "Terminal" "${terminal:-unknown} (TERM=${TERM:-unset})"
row "Editor (VISUAL/EDITOR)" "${VISUAL:-${EDITOR:-unset}}"
row "Locale" "${LANG:-unset}"
echo
echo "## Tools"
echo
echo '```text'
for spec in \
  "bash" "zsh" "fish" "git" "gh" "jq" "yq" "rg" "fd" "fzf" "curl" "make" "just" \
  "python3" "uv" "pipx" "pre-commit" "node" "npm" "pnpm" "bun" "deno" "go" "rustc" "cargo" \
  "java -version" "R" \
  "docker" "podman" "kubectl version --client" "helm version --short" "oc version --client" \
  "kind" "k3d" "terraform" \
  "shellcheck" "ruff" "mypy" "semgrep" "ast-grep" "actionlint" "mkdocs" \
  "vim" "nvim" "hx" "emacs" "code" "tmux -V" "claude" \
  "apt" "dnf" "pacman" "snap" "flatpak" "brew" "mise" "asdf" "nix"; do
  read -r -a parts <<<"$spec"
  if v=$(version "${parts[@]}"); then
    printf '%-12s %s\n' "${parts[0]}" "$(scrub "$v")"
  fi
done
echo '```'
echo
echo "## Known oddities"
echo
echo "<!-- Fill in, e.g. \"the sandbox can't reach the Docker socket\". -->"
