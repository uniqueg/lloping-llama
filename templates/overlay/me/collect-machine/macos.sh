#!/bin/sh
# Print a machine file (Markdown) for macOS: OS, shell, terminal, editor,
# hardware summary, and the versions of common tools, for
# <overlay>/me/machine.md. Read-only; prints to stdout, writes nothing.
# POSIX sh: runs with the default zsh (`zsh macos.sh`), the system bash 3.2
# or /bin/sh.
#
# Privacy: prints no host name, user name or home path unless you pass
# --with-identity; the home path and user name are replaced by "~" and
# "<user>" in all other output. Reads no secrets and no configuration files
# of the tools (only their --version output).
#
# Usage: sh macos.sh [--with-identity] > machine.md

# zsh does not split words by default; behave like sh
[ -n "${ZSH_VERSION:-}" ] && emulate sh

with_identity=false
case ${1:-} in
  --with-identity) with_identity=true ;;
  "") ;;
  *) echo "usage: macos.sh [--with-identity]" >&2; exit 2 ;;
esac

user=$(id -un 2>/dev/null || echo "")

# scrub: replace the home path and the user name (3+ characters, so that
# short names do not mangle output) in the text on stdin
scrub() {
  if $with_identity; then
    cat
  else
    awk -v home="${HOME:-}" -v user="$user" '
      function repl(s, from, to,    out, i) {
        if (from == "") return s
        out = ""
        while ((i = index(s, from)) > 0) {
          out = out substr(s, 1, i - 1) to
          s = substr(s, i + length(from))
        }
        return out s
      }
      { s = repl($0, home, "~"); if (length(user) >= 3) s = repl(s, user, "<user>"); print s }'
  fi
}

# row <label> <value>: one list item; "unknown" for an empty value
row() { printf -- '- %s: %s\n' "$1" "${2:-unknown}" | scrub; }

# version <tool> [args...]: first non-empty line of the tool's version output
version() {
  tool=$1
  shift
  command -v "$tool" >/dev/null 2>&1 || return 1
  [ $# -gt 0 ] || set -- --version
  # A failing version check gives no version, so that error output is never
  # printed
  if ! out=$("$tool" "$@" 2>&1 </dev/null); then
    printf 'installed (version check failed)'
    return 0
  fi
  out=$(printf '%s\n' "$out" | sed '/^[[:space:]]*$/d' | head -n 1 | cut -c 1-100)
  printf '%s' "${out:-installed}"
}

terminal=${TERM_PROGRAM:-unknown}
[ -n "${TERM_PROGRAM_VERSION:-}" ] && terminal="$terminal $TERM_PROGRAM_VERSION"
[ -n "${TMUX:-}" ] && terminal="$terminal (inside tmux)"
mem_bytes=$(sysctl -n hw.memsize 2>/dev/null)

echo "# Machine"
echo
echo "<!-- Generated by macos.sh on $(date +%Y-%m-%d). Add what a script can't know under"
echo "     \"Known oddities\". -->"
echo
echo "## System"
echo
if $with_identity; then
  row "Host name" "$(scutil --get ComputerName 2>/dev/null || hostname)"
  row "User" "$user"
  row "Home" "${HOME:-}"
fi
row "OS" "$(sw_vers -productName 2>/dev/null) $(sw_vers -productVersion 2>/dev/null) ($(sw_vers -buildVersion 2>/dev/null))"
row "Kernel" "$(uname -sr)"
row "Architecture" "$(uname -m)"
row "CPU" "$(sysctl -n machdep.cpu.brand_string 2>/dev/null)"
row "CPU cores" "$(sysctl -n hw.ncpu 2>/dev/null)"
[ -n "$mem_bytes" ] && row "Memory" "$((mem_bytes / 1024 / 1024 / 1024)) GiB"
row "Login shell" "${SHELL:-unknown}"
row "Terminal" "$terminal (TERM=${TERM:-unset})"
row "Editor (VISUAL/EDITOR)" "${VISUAL:-${EDITOR:-unset}}"
row "Locale" "${LANG:-unset}"
echo
echo "## Tools"
echo
echo '```text'
for spec in \
  "bash" "zsh" "fish" "git" "gh" "jq" "yq" "rg" "fd" "fzf" "curl" "make" "just" \
  "python3" "uv" "pipx" "pre-commit" "node" "npm" "pnpm" "bun" "deno" "go" "rustc" "cargo" \
  "java -version" "R" \
  "docker" "podman" "colima" "kubectl version --client" "helm version --short" \
  "oc version --client" "kind" "k3d" "terraform" \
  "shellcheck" "ruff" "mypy" "semgrep" "ast-grep" "actionlint" "mkdocs" \
  "vim" "nvim" "hx" "emacs" "code" "tmux -V" "claude" \
  "brew" "port" "mise" "asdf" "nix" "xcode-select -v"; do
  # Split the spec into the tool and its arguments (word splitting on purpose)
  # shellcheck disable=SC2086
  set -- $spec
  if v=$(version "$@"); then
    printf '%-12s %s\n' "$1" "$v" | scrub
  fi
done
echo '```'
echo
echo "## Known oddities"
echo
echo "<!-- Fill in, e.g. \"Docker runs in Colima\". -->"
