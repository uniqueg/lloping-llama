<#
.SYNOPSIS
Print a machine file (Markdown) for Windows.

.DESCRIPTION
Prints OS, shell, terminal, editor, hardware summary, WSL distributions and
the versions of common tools, for <overlay>/me/machine.md. Read-only; prints
to stdout, writes nothing. Works in Windows PowerShell 5.1 and PowerShell 7.

Privacy: prints no computer name, user name or home path unless you pass
-WithIdentity; the home path and user name are replaced by "~" and "<user>"
in all other output. Reads no secrets and no configuration files of the
tools (only their --version output).

linux.sh, macos.sh and windows.ps1 share helpers and the tool list by copy
(each runs on its own): change all three together.

.PARAMETER WithIdentity
Also print the computer name, user name and home path, and keep them in the
tool output.

.EXAMPLE
powershell -ExecutionPolicy Bypass -File windows.ps1 > machine.md
#>
[CmdletBinding()]
param(
    [switch]$WithIdentity
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Continue'

$user = $env:USERNAME
$userHome = $env:USERPROFILE

function Hide-Identity {
    <# Replace the home path and the user name (3+ characters) in a string. #>
    param([string]$Text)
    if ($WithIdentity -or -not $Text) { return $Text }
    if ($userHome) { $Text = $Text.Replace($userHome, '~') }
    if ($user -and $user.Length -ge 3) { $Text = $Text.Replace($user, '<user>') }
    return $Text
}

function Write-Row {
    <# Print one list item; "unknown" for an empty value. #>
    param([string]$Label, [string]$Value)
    if (-not $Value) { $Value = 'unknown' }
    Write-Output ("- {0}: {1}" -f $Label, (Hide-Identity $Value))
}

function Get-ToolVersion {
    <# First non-empty line of a tool's version output, or $null if missing. #>
    param([string]$Tool, [string[]]$Arguments = @('--version'))
    # Applications only: aliases such as curl or r would run cmdlets instead
    if (-not (Get-Command $Tool -CommandType Application -ErrorAction SilentlyContinue)) { return $null }
    try {
        $out = & $Tool @Arguments 2>&1 | ForEach-Object { "$_" }
        if ($LASTEXITCODE -ne 0) { return 'installed (version check failed)' }
        $line = $out | Where-Object { $_.Trim() } | Select-Object -First 1
        if (-not $line) { return 'installed' }
        if ($line.Length -gt 100) { $line = $line.Substring(0, 100) }
        return $line
    } catch {
        return 'installed (version check failed)'
    }
}

$os = Get-CimInstance -ClassName Win32_OperatingSystem -ErrorAction SilentlyContinue
$cs = Get-CimInstance -ClassName Win32_ComputerSystem -ErrorAction SilentlyContinue

$terminal = 'unknown'
if ($env:WT_SESSION) { $terminal = 'Windows Terminal' }
elseif ($env:TERM_PROGRAM) { $terminal = $env:TERM_PROGRAM }
elseif ($Host.Name -eq 'ConsoleHost') { $terminal = 'console host (conhost)' }

$editor = $env:VISUAL
if (-not $editor) { $editor = $env:EDITOR }
if (-not $editor) { $editor = 'unset' }

Write-Output '# Machine'
Write-Output ''
Write-Output ("<!-- Generated by windows.ps1 on {0}. Add what a script can't know under" -f (Get-Date -Format 'yyyy-MM-dd'))
Write-Output '     "Known oddities". -->'
Write-Output ''
Write-Output '## System'
Write-Output ''
if ($WithIdentity) {
    Write-Row 'Computer name' $env:COMPUTERNAME
    Write-Row 'User' $user
    Write-Row 'Home' $userHome
}
if ($os) {
    Write-Row 'OS' ("{0} {1} (build {2})" -f $os.Caption, $os.Version, $os.BuildNumber)
} else {
    Write-Row 'OS' ([System.Environment]::OSVersion.VersionString)
}
Write-Row 'Architecture' $env:PROCESSOR_ARCHITECTURE
Write-Row 'CPU cores' "$env:NUMBER_OF_PROCESSORS"
if ($cs) { Write-Row 'Memory' ("{0} GiB" -f [math]::Round($cs.TotalPhysicalMemory / 1GB)) }
Write-Row 'PowerShell' ("{0} {1}" -f $PSVersionTable.PSEdition, $PSVersionTable.PSVersion)
Write-Row 'Terminal' $terminal
Write-Row 'Editor (VISUAL/EDITOR)' $editor
Write-Row 'Culture' (Get-Culture).Name

if (Get-Command wsl.exe -ErrorAction SilentlyContinue) {
    # wsl.exe prints UTF-16; drop the NUL characters it leaves in PowerShell 5.1
    $distros = (& wsl.exe --list --quiet 2>$null) -replace "`0", '' | Where-Object { $_.Trim() }
    if ($distros) { Write-Row 'WSL distributions' ($distros -join ', ') }
}

Write-Output ''
Write-Output '## Tools'
Write-Output ''
Write-Output '```text'
$tools = @(
    @('pwsh'), @('git'), @('gh'), @('jq'), @('yq'), @('rg'), @('fd'), @('fzf'),
    @('curl.exe'), @('make'), @('just'),
    @('python'), @('py'), @('uv'), @('pipx'), @('pre-commit'), @('node'), @('npm'),
    @('pnpm'), @('bun'), @('deno'), @('go', 'version'), @('rustc'), @('cargo'),
    @('java', '-version'), @('R.exe'),
    @('docker'), @('podman'), @('kubectl', 'version', '--client'),
    @('helm', 'version', '--short'), @('oc', 'version', '--client'), @('kind'), @('k3d'),
    @('terraform'), @('shellcheck'), @('ruff'), @('mypy'), @('semgrep'), @('ast-grep'),
    @('actionlint'), @('mkdocs'),
    @('vim'), @('nvim'), @('hx'), @('code'), @('claude'),
    @('winget'), @('choco'), @('scoop')
)
foreach ($spec in $tools) {
    $tool = $spec[0]
    $arguments = if ($spec.Count -gt 1) { [string[]]$spec[1..($spec.Count - 1)] } else { @('--version') }
    $version = Get-ToolVersion -Tool $tool -Arguments $arguments
    if ($null -ne $version) {
        Write-Output ("{0,-12} {1}" -f $tool, (Hide-Identity $version))
    }
}
Write-Output '```'
Write-Output ''
Write-Output '## Known oddities'
Write-Output ''
Write-Output '<!-- Fill in, e.g. "Docker runs in WSL 2". -->'
